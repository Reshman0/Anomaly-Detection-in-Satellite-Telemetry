const GLYPH_W = 5;
/**
 * 8 satir cizilir (7 degil): `g p q y j` alt uzantilarini ve `s c` sedillalarini
 * tasiyan 8. bit aksi halde kirpilir ve `g` harfi `9` gibi gorunur.
 */
const GLYPH_H = 8;

export class Canvas {
  /**
   * @param w,h  Tasarim birimi cinsinden olculer (1x).
   * @param olcek Cikti cozunurlugu carpani. Cizim kodu hep 1x biriminde
   *        calisir; buyutulmus gorunum icin 2x uretmek yeterlidir, tum
   *        koordinatlari tek tek olceklemek gerekmez.
   */
  constructor(w, h, bg = [11, 16, 20], olcek = 1) {
    this.w = w;
    this.h = h;
    this.s = Math.max(1, Math.round(olcek));
    this.pw = w * this.s;
    this.ph = h * this.s;
    this.px = Buffer.alloc(this.pw * this.ph * 3);
    for (let i = 0; i < this.pw * this.ph; i++) {
      this.px[i * 3] = bg[0];
      this.px[i * 3 + 1] = bg[1];
      this.px[i * 3 + 2] = bg[2];
    }
  }

  /** Gercek piksel yazar (olcek uygulanmaz). */
  _pset(x, y, c) {
    if (x < 0 || y < 0 || x >= this.pw || y >= this.ph) return;
    const i = (y * this.pw + x) * 3;
    this.px[i] = c[0];
    this.px[i + 1] = c[1];
    this.px[i + 2] = c[2];
  }

  /** Tasarim birimi cinsinden tek nokta — olcek kadar blok doldurur. */
  set(x, y, c) {
    x = Math.round(x) * this.s;
    y = Math.round(y) * this.s;
    for (let j = 0; j < this.s; j++) for (let i = 0; i < this.s; i++) this._pset(x + i, y + j, c);
  }

  rect(x, y, w, h, c) {
    const x0 = Math.round(x) * this.s;
    const y0 = Math.round(y) * this.s;
    const w0 = Math.round(w) * this.s;
    const h0 = Math.round(h) * this.s;
    for (let j = 0; j < h0; j++) for (let i = 0; i < w0; i++) this._pset(x0 + i, y0 + j, c);
  }

  /** Cerceve (dolgusuz dikdortgen). */
  frame(x, y, w, h, c) {
    this.rect(x, y, w, 1, c);
    this.rect(x, y + h - 1, w, 1, c);
    this.rect(x, y, 1, h, c);
    this.rect(x + w - 1, y, 1, h, c);
  }

  line(x0, y0, x1, y1, c) {
    x0 |= 0;
    y0 |= 0;
    x1 |= 0;
    y1 |= 0;
    const dx = Math.abs(x1 - x0);
    const dy = -Math.abs(y1 - y0);
    const sx = x0 < x1 ? 1 : -1;
    const sy = y0 < y1 ? 1 : -1;
    let err = dx + dy;
    for (;;) {
      this.set(x0, y0, c);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * err;
      if (e2 >= dy) {
        err += dy;
        x0 += sx;
      }
      if (e2 <= dx) {
        err += dx;
        y0 += sy;
      }
    }
  }

  /** Kalin cizgi (dikey kalinlik). */
  thickLine(x0, y0, x1, y1, c, t = 2) {
    for (let k = 0; k < t; k++) this.line(x0, y0 + k, x1, y1 + k, c);
  }

  text(x, y, str, c, scale = 1) {
    let cx = x;
    for (const ch of String(str)) {
      const g = FONT[ch] ?? FONT['.'];
      for (let col = 0; col < GLYPH_W; col++) {
        for (let row = 0; row < GLYPH_H; row++) {
          if ((g[col] >> row) & 1) {
            this.rect(cx + col * scale, y + row * scale, scale, scale, c);
          }
        }
      }
      cx += (GLYPH_W + 1) * scale;
    }
    return cx - x;
  }

  textWidth(str, scale = 1) {
    return String(str).length * (GLYPH_W + 1) * scale;
  }

  textRight(xRight, y, str, c, scale = 1) {
    this.text(xRight - this.textWidth(str, scale), y, str, c, scale);
  }

  toPng() {
    const raw = Buffer.alloc((this.pw * 3 + 1) * this.ph);
    for (let y = 0; y < this.ph; y++) {
      raw[y * (this.pw * 3 + 1)] = 0; // filter: none
      this.px.copy(raw, y * (this.pw * 3 + 1) + 1, y * this.pw * 3, (y + 1) * this.pw * 3);
    }
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.pw, 0);
    ihdr.writeUInt32BE(this.ph, 4);
    ihdr[8] = 8; // bit depth
    ihdr[9] = 2; // truecolor
    return Buffer.concat([
      Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
      chunk('IHDR', ihdr),
      chunk('IDAT', deflateSync(raw, { level: 9 })),
      chunk('IEND', Buffer.alloc(0)),
    ]);
  }
}

/** Siyah -> kirmizi -> turuncu -> sari -> beyaz isi rengi. */
export function heat(t) {
  const stops = [
    [0.0, [12, 8, 14]],
    [0.25, [110, 14, 26]],
    [0.5, [214, 58, 24]],
    [0.75, [246, 168, 38]],
    [1.0, [255, 248, 214]],
  ];
  t = Math.max(0, Math.min(1, t));
  for (let i = 1; i < stops.length; i++) {
    if (t <= stops[i][0]) {
      const [t0, c0] = stops[i - 1];
      const [t1, c1] = stops[i];
      const f = (t - t0) / (t1 - t0);
      return [0, 1, 2].map((k) => Math.round(c0[k] + (c1[k] - c0[k]) * f));
    }
  }
  return stops[stops.length - 1][1];
}
